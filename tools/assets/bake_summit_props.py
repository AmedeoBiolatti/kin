#!/usr/bin/env python3
"""Bake compact collision geometry from the selected, pinned Kenney glTF files. Stdlib only."""
from pathlib import Path
import json
import struct
import hashlib

repo=Path(__file__).resolve().parents[2]
root=repo/'examples/summit/content/kenney-survival'
manifest=json.loads((root/'manifest.json').read_text())
names=['tent-canvas','campfire-pit','bedroll','bedroll-packed','box','barrel','bottle','resource-wood','tree','tree-tall','rock-a','rock-b','grass','grass-large']
solid={'tent-canvas','campfire-pit','box','barrel','resource-wood','rock-a','rock-b'}
text=['// Generated by tools/assets/bake_summit_props.py from the pinned CC0 originals; do not edit.', '#pragma once', '#include "props.hpp"', 'namespace summit::prop_geometry {']
records=[]
def f(x):
 s=format(x,'.9g')
 if '.' not in s and 'e' not in s:s+='.0'
 return s+'f'
def vec(p):return '{'+', '.join(f(x) for x in p)+'}'
for k,name in enumerate(names):
 blob=(root/(name+'.glb')).read_bytes();assert hashlib.sha256(blob).hexdigest()==manifest['files'][name+'.glb']['sha256']
 size=struct.unpack_from('<I',blob,12)[0];g=json.loads(blob[20:20+size]);binary=blob[20+size+8:]
 def read(ai):
  a=g['accessors'][ai];v=g['bufferViews'][a['bufferView']];fmt={5126:'f',5125:'I',5123:'H',5121:'B'}[a['componentType']]
  n={'VEC3':3,'SCALAR':1}[a['type']];stride=v.get('byteStride',struct.calcsize(fmt)*n)
  offset=v.get('byteOffset',0)+a.get('byteOffset',0)
  return [struct.unpack_from('<'+fmt*n,binary,offset+i*stride) for i in range(a['count'])]
 points=[];indices=[]
 parents={child:i for i,node in enumerate(g['nodes']) for child in node.get('children',[])}
 def translation(i):
  t=g['nodes'][i].get('translation',[0,0,0])
  return [a+b for a,b in zip(t,translation(parents[i]))] if i in parents else t
 for ni,node in enumerate(g['nodes']):
  if 'mesh' not in node:continue
  assert not any(x in node for x in ['matrix','rotation','scale'])
  t=translation(ni)
  for primitive in g['meshes'][node['mesh']]['primitives']:
   start=len(points);points.extend(tuple(v[i]+t[i] for i in range(3)) for v in read(primitive['attributes']['POSITION']))
   indices.extend(start+i[0] for i in read(primitive['indices']))
 lo=[min(p[i] for p in points) for i in range(3)];hi=[max(p[i] for p in points) for i in range(3)]
 bottom=[(lo[0]+hi[0])/2,lo[1],(lo[2]+hi[2])/2];extent=max(hi[i]-lo[i] for i in range(3))
 normalized=[tuple((p[i]-bottom[i])/extent for i in range(3)) for p in points]
 if name in solid:
  unique=list(dict.fromkeys(normalized));lookup={p:i for i,p in enumerate(unique)}
  indices=[lookup[normalized[i]] for i in indices]
  text.append(f'inline constexpr Vec3f points_{k}[] = {{'+', '.join(vec(p) for p in unique)+'};')
  if name in {'tent-canvas','campfire-pit'}:
   text.append(f'inline constexpr u32 indices_{k}[] = {{'+', '.join(map(str,indices))+'};')
   records.append('{'+vec(lo)+', '+vec(hi)+f', points_{k}, indices_{k}'+'}')
  else:records.append('{'+vec(lo)+', '+vec(hi)+f', points_{k}, {{}}'+'}')
 else:records.append('{'+vec(lo)+', '+vec(hi)+', {}, {}}')
text.append('inline const std::array<PropGeometry, PropCount> all{{'+',\n'.join(records)+'}};')
text.append('} // namespace summit::prop_geometry\n')
destination=repo/'examples/summit/prop_geometry.hpp'
output='\n'.join(text)
if not destination.exists() or destination.read_text()!=output:destination.write_text(output)
print('Baked source bounds and normalized collision geometry for',len(solid),'solid models')
