#!/usr/bin/env python3
"""Writes engine/src/renderer/gpu/gpu_area_lights_ltc.cpp, the area lights' linearly transformed cosines tables,
from three.js r160's examples/jsm/lights/RectAreaLightUniformsLib.js (MIT) and three.js's LICENSE.

    gen_area_light_ltc.py <RectAreaLightUniformsLib.js> <three.js LICENSE>
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    js, license_file = (Path(p).read_text(encoding='utf-8') for p in sys.argv[1:3])
    tables = []
    for name in ('LTC_MAT_1', 'LTC_MAT_2'):
        m = re.search(r'const ' + name + r' = \[([^\]]*)\];', js)
        vals = [float(x.replace(' ', '')) for x in m.group(1).split(',') if x.strip()]
        assert len(vals) == 64 * 64 * 4, (name, len(vals))
        tables.append(vals)
    notice = [('// ' + line).rstrip() for line in license_file.strip().splitlines()]
    out = ['// Linearly transformed cosines (Heitz, Dupuy, Hill, Neubelt 2016: "Real-Time Polygonal-Light Shading with',
           '// Linearly Transformed Cosines"): the GGX fit\'s two 64 x 64 RGBA tables, as three.js r160 ships them',
           '// (examples/jsm/lights/RectAreaLightUniformsLib.js, LTC_MAT_1 then LTC_MAT_2), under three.js\'s license:',
           '//'] + notice + [
           '//',
           '// Row by row of sqrt(1 - cos(view, normal)), each from roughness 0 to 1. Generated by',
           '// tools/gen_area_light_ltc.py.',
           '#include "gpu_area_lights3d.hpp"', '', 'namespace kin::gpu {', '',
           'extern const float area_light_ltc[area_light_ltc_floats] = {']
    vals = tables[0] + tables[1]
    for i in range(0, len(vals), 8):
        out.append('    ' + ', '.join(repr(float(v)) + 'f' for v in vals[i:i + 8]) + ',')
    out += ['};', '', '} // namespace kin::gpu', '']
    (ROOT / 'engine/src/renderer/gpu/gpu_area_lights_ltc.cpp').write_text('\n'.join(out), encoding='utf-8')
    print('values', len(vals))


if __name__ == '__main__':
    main()
