#!/usr/bin/env python3
"""Bake printable ASCII into a Kin C++ font header (development only: Pillow).

The font's redistribution notice must accompany the generated header/package.
No Pillow, font file or image codec is needed to build or run that game.
"""
import argparse
import hashlib
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont, __version__ as pillow_version


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--size", type=int, default=15)
    args = parser.parse_args()
    font = ImageFont.truetype(str(args.font), args.size)
    alphabet = [chr(c) for c in range(32, 127)]
    width = 256
    glyphs = []
    x = y = 1
    row_height = 0
    for char in alphabet:
        left, top, right, bottom = font.getbbox(char)
        w, h = right - left, bottom - top
        if x + w + 1 > width:
            x, y, row_height = 1, y + row_height + 2, 0
        glyphs.append((char, x, y, w, h, left, top, font.getlength(char)))
        x += w + 2
        row_height = max(row_height, h)
    atlas = Image.new("L", (width, y + row_height + 1))
    draw = ImageDraw.Draw(atlas)
    for char, x, y, w, h, left, top, advance in glyphs:
        draw.text((x - left, y - top), char, font=font, fill=255)
    rle = []
    for alpha in atlas.tobytes():
        if rle and alpha == rle[-1] and rle[-2] < 255:
            rle[-2] += 1
        else:
            rle.extend((1, alpha))
    kern = []
    for left in alphabet:
        for right in alphabet:
            adjustment = font.getlength(left + right) - font.getlength(left) - font.getlength(right)
            if adjustment:
                kern.append((ord(left), ord(right), adjustment))
    lines = ["// Generated by tools/bake_font.py; do not edit.",
             f"// {args.font.name}, {args.size}px; Pillow {pillow_version}.",
             f"// Font SHA256: {hashlib.sha256(args.font.read_bytes()).hexdigest()}",
             "#pragma once", "#include <kin/ui2/baked_font.hpp>", "#include <array>",
             "namespace demo::hud_font {", "inline constexpr kin::u8 alpha[] = {"]
    lines += ["    " + ",".join(map(str, rle[i:i + 32])) + "," for i in range(0, len(rle), 32)]
    lines += ["};", "inline constexpr kin::ui2::BakedGlyph glyphs[] = {"]
    for char, x, y, w, h, left, top, advance in glyphs:
        lines.append(f"    {{{ord(char)}, {{{x},{y},{w},{h}}}, {{{left}.0f,{top}.0f}}, {advance}f}},")
    lines += ["};", f"inline constexpr std::array<kin::ui2::BakedKerning, {len(kern)}> kerning{{{{"]
    lines += [f"    {{{left},{right},{value}f}}," for left, right, value in kern]
    lines += ["}};", "inline kin::ui2::Font get() {",
              f"    static const auto font = kin::ui2::baked_font({{{{{atlas.width},{atlas.height}}},",
              f"        {sum(font.getmetrics())}.0f, alpha, glyphs, kerning}});",
              "    return font;", "}", "} // namespace demo::hud_font", ""]
    args.output.write_text("\n".join(lines))
    print(f"{len(glyphs)} glyphs, {len(kern)} kerning pairs, {len(rle)} coverage bytes")


if __name__ == "__main__":
    main()
